import { Router } from 'express';
import * as c from './automations.controller.js';
import * as v from './automations.validator.js';
import { validate } from '../../middleware/validationMiddleware.js';
import { requireAuth } from '../../middleware/authMiddleware.js';
import { salesScope } from '../../middleware/salesIdMiddleware.js';
const router = Router();
const p = validate({ params: v.idParams });
router.use(requireAuth, salesScope);
router.get('/', validate({ query: v.listQuery }), c.list);
router.post('/', validate({ body: v.createSchema }), c.create);
router.get('/:id', p, c.get);
router.put('/:id', validate({ params: v.idParams, body: v.updateSchema }), c.update);
router.post('/:id/activate', p, c.activate);
router.post('/:id/pause', p, c.pause);
router.delete('/:id', p, c.remove);
router.post('/:id/enroll', validate({ params: v.idParams, body: v.enrollSchema }), c.enroll);
router.get('/:id/enrollments', validate({ params: v.idParams, query: v.listQuery }), c.enrollments);
router.get('/:id/executions', validate({ params: v.idParams, query: v.logQuery }), c.executions);
export default router;
